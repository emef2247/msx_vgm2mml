"""Y8950 (MSX-AUDIO) projection for the msxaudio cartridge profile.

The Y8950 FM section is a two-operator OPL core with nine channels
and a native rhythm unit.  OPLL melody voices map through the
commercially observed conversion table (data/presets/msxaudio/
opll_to_y8950.json, generated by make_presets.py from
opl_commercial.json): the voicing Compile's MSX dual-edition games
used, with the carrier level as a performance value (source
VOL << 2).  Custom patches, which the commercial games mapped by
field identity, still project through the established set's OPL
frame.  OPLL percussion projects to the native rhythm unit with
the commercially observed voice template.  Y8950 sources re-emit
their retained native voices and rhythm.
"""
from collections import Counter
import json
import math
from pathlib import Path

from musical_fm_target import _at
from opll_fm_target import _decode_patch

_PRESET_DIR = Path(__file__).resolve().parent.parent / 'data' / 'presets'
_OFFSETS = [(ch // 3) * 8 + (ch % 3) for ch in range(9)]
_KSL_REFRAME = {0: 0, 1: 2, 2: 1, 3: 3}
_OP_FIELDS = ('am', 'vib', 'egt', 'ksr', 'mul', 'ksl', 'tl',
              'ar', 'dr', 'sl', 'rr')
_RHYTHM_BITS = (('BD', 16), ('SD', 8), ('TOM', 4), ('CYM', 2), ('HH', 1))
_RHYTHM_TL = {'BD': 0x53, 'SD': 0x54, 'TOM': 0x52, 'CYM': 0x55, 'HH': 0x51}
_RHYTHM_PITCH_CH = {'BD': 6, 'TOM': 8}
_cache = {}


def _table():
    if 'y8950' not in _cache:
        doc = json.loads((_PRESET_DIR / 'msxaudio' / 'opll_to_y8950.json').read_text())
        _cache['y8950'] = (doc, {v['index']: v for v in doc['voices']})
    return _cache['y8950']


def _commercial_rhythm():
    if 'commercial_rhythm' not in _cache:
        doc = json.loads((_PRESET_DIR / 'opl_commercial.json').read_text())
        _cache['commercial_rhythm'] = doc['rhythm_template']
    return _cache['commercial_rhythm']


def _pitch(hz, clock):
    for block in range(8):
        fnum = round(hz * 144 * 2 ** (19 - block) / clock)
        if fnum <= 1023:
            return block, max(1, fnum)
    return 7, 1023


def _identity_op(o):
    """Established-set op dict (patch schema) -> OPL-frame tuple."""
    return (o['am'], o['vib'], o['egt'], o['ksr'], o['multi'],
            _KSL_REFRAME[o['ksl']], o['tl'] or 0,
            o['ar'], o['dr'], o['sl'], o['rr'])


def project_opl_fm(performance, *, force=False):
    """Project OPLL and Y8950 sources to Y8950 FM/rhythm writes.

    Returns (rows, losses, allocation).  Only the first device of
    each source family is projected, mirroring the native lanes.
    A resolved voice row is (feedback, ops[, connection]); ops are
    (am, vib, egt, ksr, mul, ksl, tl, ar, dr, sl, rr) tuples whose
    tl is the modulator's absolute level or the carrier's level
    relative to the unit's volume curve.
    """
    voice_by_id = {v.voice_id: v for v in performance.voices}
    rows, losses = [], Counter()
    allocation = {}

    def emit(unit, sample, order, register, value, reason, device_id=None):
        rows.append(dict(sample=sample, order=order,
                         command=bytes((0x5c, register, value & 255)),
                         unit_id=unit.unit_id if unit else '',
                         device_id=device_id or (unit.device_id if unit else ''),
                         source_indices=unit.source_indices if unit else (),
                         reason=reason))

    def run_units(device, units, resolve, tl_of, carrier_tl, missing_loss):
        lanes = sorted({(u.device_id, u.channel) for u in units})
        local = {}
        for lane in lanes:
            free = [ch for ch in range(9)
                    if ch not in local.values() and ch not in allocation.values()]
            if free:
                local[lane] = lane[1] if lane[1] in free else free[0]
        if len(local) < len(lanes) and not force:
            raise ValueError('Y8950 FM target capacity exceeded; force permits explicitly reported lane omission')
        allocation.update({str(k): v for k, v in local.items()})
        clock = device.clock_hz or 3579545
        for unit in units:
            lane = (unit.device_id, unit.channel)
            if lane not in local:
                losses['opl_fm_units_omitted_capacity'] += 1
                continue
            pitch_values = [_at(unit.pitch_curve, unit.start_sample),
                            *(hz for at, hz in unit.pitch_curve
                              if unit.start_sample <= at < unit.end_sample)]
            if any(hz is None or not math.isfinite(hz) or hz <= 0
                   for hz in pitch_values):
                losses[missing_loss] += 1
                continue
            ch = local[lane]
            off = _OFFSETS[ch]
            times = sorted({unit.start_sample,
                            *(at for curve in (unit.pitch_curve, unit.volume_curve,
                                               unit.voice_curve)
                              for at, _ in curve
                              if unit.start_sample <= at < unit.end_sample)})
            state = {'pitch': None}
            previous = (object(), object(), object())

            def emit_voice(sample, row, level):
                fb, ops = row[0], row[1]
                for slot, op in enumerate(ops):
                    o = off + 3 * slot
                    emit(unit, sample, -0.5, 0x20 + o,
                         (op[0] << 7) | (op[1] << 6) | (op[2] << 5) | (op[3] << 4) | op[4],
                         'OPL voice operator flags')
                    emit(unit, sample, -0.5, 0x40 + o,
                         (op[5] << 6) | tl_of(row, slot, op, level),
                         'OPL voice operator level')
                    emit(unit, sample, -0.5, 0x60 + o, (op[7] << 4) | op[8],
                         'OPL voice operator attack/decay')
                    emit(unit, sample, -0.5, 0x80 + o, (op[9] << 4) | op[10],
                         'OPL voice operator sustain/release')
                emit(unit, sample, -0.5, 0xc0 + ch, fb << 1, 'OPL voice feedback')

            def emit_pitch(sample, hz):
                block, fnum = _pitch(hz, clock)
                state['pitch'] = (block, fnum)
                emit(unit, sample, -0.5, 0xa0 + ch, fnum & 255, 'OPL pitch low')
                emit(unit, sample, -0.5, 0xb0 + ch,
                     (1 << 5) | (block << 2) | (fnum >> 8), 'OPL pitch high/key')

            for sample in times:
                voice_id = _at(unit.voice_curve, sample)
                row = resolve(voice_id)
                if row is None:
                    losses['opl_missing_voice'] += 1
                    continue
                level = _at(unit.volume_curve, sample)
                hz = _at(unit.pitch_curve, sample)
                if voice_id != previous[0]:
                    emit_voice(sample, row, level)
                elif level != previous[1]:
                    carrier_tl(unit, sample, ch, row, level, emit)
                if hz != previous[2]:
                    emit_pitch(sample, hz)
                previous = (voice_id, level, hz)
            if state['pitch'] is not None:
                block, fnum = state['pitch']
                emit(unit, unit.end_sample,
                     -1 if unit.end_sample > unit.start_sample else 1,
                     0xb0 + ch, (block << 2) | (fnum >> 8), 'OPL gate end')

    # ---- OPLL melody -------------------------------------------------
    opll_devices = [d for d in performance.devices if d.chip == 'opll']
    if opll_devices:
        device = opll_devices[0]
        if len(opll_devices) > 1:
            losses['second_opll_device_melody_not_fm_projected'] += 1
        _doc, table = _table()
        resolved = {}

        def resolve_opll(voice_id):
            if voice_id in resolved:
                return resolved[voice_id]
            voice = voice_by_id.get(voice_id)
            p = dict(voice.parameters) if voice else {}
            inst = p.get('instrument')
            result = None
            if inst and inst in table:
                entry = table[inst]
                result = (entry['fb'],
                          [tuple(o[f] for f in _OP_FIELDS) for o in entry['ops']])
            elif inst == 0:
                patch = p.get('custom_patch') or ()
                if any(b is None for b in patch):
                    losses['opll_custom_patch_bytes_unobserved'] += 1
                patch = tuple(0 if b is None else b for b in patch)
                patch = patch + (0,) * (8 - len(patch))
                decoded = _decode_patch(patch)
                result = (decoded['fb'], [_identity_op(decoded['mod']),
                                          _identity_op(decoded['car'])])
            resolved[voice_id] = result
            return result

        def tl_opll(row, slot, op, level):
            if slot == 0:
                return op[6]
            level = 15 if level is None else max(0, min(15, int(level)))
            return min(63, level << 2)

        def carrier_opll(unit, sample, ch, row, level, emit):
            level = 15 if level is None else max(0, min(15, int(level)))
            emit(unit, sample, -0.5, 0x40 + _OFFSETS[ch] + 3,
                 (row[1][1][5] << 6) | min(63, level << 2), 'OPL carrier level')

        run_units(device,
                  [u for u in performance.units
                   if u.device_id == device.device_id and u.section == 'fm'],
                  resolve_opll, tl_opll, carrier_opll,
                  'opll_unknown_pitch_units_muted')
        _project_rhythm(performance, device, emit, losses)

    # ---- Y8950 native ------------------------------------------------
    y8950_devices = [d for d in performance.devices if d.chip == 'y8950']
    if y8950_devices:
        device = y8950_devices[0]
        if len(y8950_devices) > 1:
            losses['second_y8950_device_omitted'] += 1
        resolved = {}

        def resolve_native(voice_id):
            if voice_id in resolved:
                return resolved[voice_id]
            voice = voice_by_id.get(voice_id)
            p = dict(voice.parameters) if voice else {}
            result = None
            if 'operators' in p:
                ops = []
                for raw in p['operators']:
                    o = dict(raw)
                    ops.append((o['am'], o['vib'], o['egt'], o['ksr'],
                                o['multiple'], o['key_scale'], o['total_level'],
                                o['attack'], o['decay'], o['sustain_level'],
                                o['release']))
                result = (p['feedback'] or 0, ops, p['connection'] or 0)
            resolved[voice_id] = result
            return result

        def carriers_of(row):
            return (0, 1) if row[2] else (1,)

        def tl_native(row, slot, op, level):
            base = op[6] or 0
            if slot in carriers_of(row):
                level = 0 if level is None else max(0, min(63, int(level)))
                return min(63, base + level)
            return base

        def carrier_native(unit, sample, ch, row, level, emit):
            for slot in carriers_of(row):
                op = row[1][slot]
                emit(unit, sample, -0.5,
                     0x40 + _OFFSETS[ch] + 3 * slot,
                     (op[5] << 6) | tl_native(row, slot, op, level),
                     'OPL carrier level')

        run_units(device,
                  [u for u in performance.units
                   if u.device_id == device.device_id and u.section == 'fm'],
                  resolve_native, tl_native, carrier_native,
                  'y8950_unknown_pitch_units_muted')
        _project_rhythm(performance, device, emit, losses)

    return rows, losses, allocation


def _project_rhythm(performance, device, emit, losses):
    events = [e for e in performance.percussion if e.device_id == device.device_id]
    if not events:
        return
    bits = dict(_RHYTHM_BITS)
    actions = []
    for e in events:
        if e.instrument_family not in bits:
            losses['opl_rhythm_family_unmapped'] += 1
            continue
        stop = e.stop_sample if e.stop_sample is not None else e.start_sample + 735
        actions.append((e.start_sample, 1, e))
        actions.append((stop, 0, e))
    actions.sort(key=lambda row: (row[0], row[1]))
    if device.chip == 'opll':
        _rhythm_template(device, emit)
        pitches = _opll_rhythm_pitches(performance, device)
    emitted = {}
    mask = 0
    for sample, is_start, e in actions:
        bit = bits[e.instrument_family]
        if is_start:
            if device.chip == 'opll':
                _opll_hit_setup(performance, device, emit, e, pitches, losses)
            else:
                _native_hit_setup(performance, device, emit, e, emitted, losses)
            mask |= bit
        else:
            mask &= ~bit
        emit(None, sample, 0, 0xbd, 0xe0 | mask, 'OPL rhythm key',
             device_id=device.device_id)


def _rhythm_template(device, emit):
    """Commercially observed rhythm voices on channels 6/7/8.

    The template bytes are the register setup the dual-edition
    games install (identical in every game measured); the five
    volume TL registers start muted and are set per hit.
    """
    template = _commercial_rhythm()
    for ch in (6, 7, 8):
        entry = template[str(ch)]
        off = _OFFSETS[ch]
        for slot, key in enumerate(('mod', 'car')):
            b20, b40, b60, b80 = entry[key]
            o = off + 3 * slot
            emit(None, 0, -2, 0x20 + o, b20,
                 'OPL rhythm voice', device_id=device.device_id)
            tl = 63 if 0x40 + o in _RHYTHM_TL.values() else (b40 & 63)
            emit(None, 0, -2, 0x40 + o, (b40 & 0xc0) | tl,
                 'OPL rhythm voice', device_id=device.device_id)
            emit(None, 0, -2, 0x60 + o, b60,
                 'OPL rhythm voice', device_id=device.device_id)
            emit(None, 0, -2, 0x80 + o, b80,
                 'OPL rhythm voice', device_id=device.device_id)
        emit(None, 0, -2, 0xc0 + ch, entry['fb_cnt'], 'OPL rhythm voice',
             device_id=device.device_id)


def _opll_rhythm_pitches(performance, device):
    """(sample, {channel: (fnum, block)}) snapshots from typed controls."""
    state = {}
    result = []
    for c in performance.controls:
        if c.device_id != device.device_id:
            continue
        p = dict(c.parameters)
        if c.kind == 'opll_pitch_low':
            fnum, block = state.get(c.channel, (0, 0))
            state[c.channel] = (p['fnum_low'] | (fnum & 0x100), block)
        elif c.kind == 'opll_pitch_high':
            fnum, block = state.get(c.channel, (0, 0))
            state[c.channel] = ((fnum & 0xff) | (p['fnum_high'] << 8), p['block'])
        result.append((c.sample, dict(state)))
    return result


def _opll_hit_setup(performance, device, emit, e, pitches, losses):
    family = e.instrument_family
    for at, level in e.volume_curve:
        if level is None:
            continue
        # Same dB law as the melody carriers: TL = att << 2.  No
        # rhythm-specific offset is established (the one candidate
        # reading rested on the wrong nibble of the shared volume
        # register; see the Famista pairing notes).
        emit(None, at, -0.5, _RHYTHM_TL[family],
             min(63, int(level) << 2), 'OPL rhythm level',
             device_id=device.device_id)
    if not e.volume_curve:
        losses['opll_rhythm_level_unobserved'] += 1
    ch = _RHYTHM_PITCH_CH.get(family)
    if ch is not None:
        state = {}
        for sample, snapshot in pitches:
            if sample > e.start_sample:
                break
            state = snapshot
        fnum, block = state.get(ch, (None, None))
        if fnum is None:
            losses['opll_rhythm_pitch_unobserved'] += 1
        else:
            clock = device.clock_hz or 3579545
            hz = fnum * clock / 72 * 2 ** block / 2 ** 19
            block2, fnum2 = _pitch(hz, 3579545)
            emit(None, e.start_sample, -0.5, 0xa0 + ch, fnum2 & 255,
                 'OPL rhythm pitch', device_id=device.device_id)
            emit(None, e.start_sample, -0.5, 0xb0 + ch,
                 (block2 << 2) | (fnum2 >> 8), 'OPL rhythm pitch',
                 device_id=device.device_id)


def _native_hit_setup(performance, device, emit, e, emitted, losses):
    """Re-emit the source's rhythm-channel state observed at the hit."""
    from native_registers import encode_control
    controls = {c.control_id: c for c in performance.controls}
    start_order = None
    if e.control_ids:
        first = controls.get(e.control_ids[0])
        if first is not None:
            start_order = first.order
    registers = {}
    for c in performance.controls:
        if c.device_id != device.device_id:
            continue
        if c.sample > e.start_sample:
            break
        if (c.sample == e.start_sample and start_order is not None
                and c.order >= start_order):
            continue
        encoded = encode_control(c, device)
        registers[encoded[1]] = encoded[2]
    for ch in (6, 7, 8):
        off = _OFFSETS[ch]
        for register in ([0x20 + off + 3 * s + group
                          for group in (0, 0x20, 0x40, 0x60)
                          for s in (0, 1)]
                         + [0xc0 + ch, 0xa0 + ch, 0xb0 + ch]):
            if register not in registers:
                continue
            value = registers[register]
            if register == 0xb0 + ch:
                value &= 0x1f
            if emitted.get(register) != value:
                emit(None, e.start_sample, -0.5, register, value,
                     'OPL rhythm voice state', device_id=device.device_id)
                emitted[register] = value
    for at, level in e.volume_curve:
        if level is None:
            continue
        register = _RHYTHM_TL[e.instrument_family]
        value = min(63, int(level))
        emit(None, at, -0.5, register, value, 'OPL rhythm level',
             device_id=device.device_id)
        emitted[register] = value
