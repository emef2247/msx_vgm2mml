"""YMF262 (OPL3) projection for the opl3 cartridge profile.

The OPL3 is a superset of the Y8950's OPL core: eighteen two-op
channels in two register banks, six of them pairable into four-op
voices, per-operator waveform select and per-channel stereo.  OPLL
melody voices map through the commercially observed conversion
table (data/presets/opl3/opll_to_opl3.json, generated by
make_presets.py from opl_commercial.json) with the carrier level
as a performance value (source VOL << 2); custom patches keep the
field-identity projection the commercial games used.  OPLL
percussion projects to the bank-0 rhythm unit with the
commercially observed voice template.  Y8950 sources re-emit on
bank 0 (overflow to bank 1); YMF262 sources re-emit on their own
channels, four-op pairs included.  Four-op FM sources (OPM/OPNA/
OPN2) and waveform sources have no OPL3 projection yet; the
profile reports them unavailable instead of approximating.
"""
from collections import Counter
import json
import math
from pathlib import Path

from musical_fm_target import _at
from musical_opl_target import _identity_op, _commercial_rhythm
from opll_fm_target import _decode_patch

_PRESET_DIR = Path(__file__).resolve().parent.parent / 'data' / 'presets'
_OFFSETS = [(ch // 3) * 8 + (ch % 3) for ch in range(9)]
_OP_FIELDS = ('am', 'vib', 'egt', 'ksr', 'mul', 'ksl', 'tl',
              'ar', 'dr', 'sl', 'rr')
_RHYTHM_BITS = (('BD', 16), ('SD', 8), ('TOM', 4), ('CYM', 2), ('HH', 1))
_RHYTHM_TL = {'BD': 0x53, 'SD': 0x54, 'TOM': 0x52, 'CYM': 0x55, 'HH': 0x51}
_RHYTHM_PITCH_CH = {'BD': 6, 'TOM': 8}
_cache = {}


def _table():
    if 'opl3' not in _cache:
        doc = json.loads((_PRESET_DIR / 'opl3' / 'opll_to_opl3.json').read_text())
        _cache['opl3'] = (doc, {v['index']: v for v in doc['voices']})
    return _cache['opl3']


def _pitch(hz, clock):
    for block in range(8):
        fnum = round(hz * 288 * 2 ** (20 - block) / clock)
        if fnum <= 1023:
            return block, max(1, fnum)
    return 7, 1023


def _command(ch, register, value):
    return bytes((0x5f if ch >= 9 else 0x5e, register, value & 255))


def _op_owner(ch, slot):
    """(channel, slot) owning chain operator `slot` of a 4-op unit."""
    if slot % 2 == 0:
        return ch, slot // 2
    return ch + 1, slot // 2


def project_opl3_fm(performance, *, force=False):
    """Project OPLL, Y8950 and YMF262 sources to YMF262 writes.

    Returns (rows, losses, allocation).  Resolved voice rows are
    (feedback, ops, connection, left, right); ops are
    (am, vib, egt, ksr, mul, ksl, tl, ar, dr, sl, rr, waveform)
    tuples in chain order.
    """
    voice_by_id = {v.voice_id: v for v in performance.voices}
    rows, losses = [], Counter()
    allocation = {}
    reserved = set()

    def emit(unit, sample, order, ch, register, value, reason, device_id=None):
        rows.append(dict(sample=sample, order=order,
                         command=_command(ch, register, value),
                         unit_id=unit.unit_id if unit else '',
                         device_id=device_id or (unit.device_id if unit else ''),
                         source_indices=unit.source_indices if unit else (),
                         reason=reason))

    def emit_setup(register, value, bank, reason):
        rows.append(dict(sample=0, order=-2,
                         command=bytes((0x5f if bank else 0x5e, register, value & 255)),
                         unit_id='', device_id='', source_indices=(),
                         reason=reason))

    # YMF262 native lanes keep their channels; 4-op primaries also
    # reserve their secondary channel.
    native_devices = [d for d in performance.devices if d.chip == 'ymf262']
    for device in native_devices:
        for unit in performance.units:
            if unit.device_id != device.device_id or unit.section != 'fm':
                continue
            voice = voice_by_id.get(_at(unit.voice_curve, unit.start_sample))
            ops = dict(voice.parameters).get('operators', ()) if voice else ()
            reserved.add(unit.channel)
            if len(ops) == 4:
                reserved.add(unit.channel + 1)
    pair_mask = 0
    for ch in reserved:
        bank, local = divmod(ch, 9)
        if local in (1, 4, 7) and (ch - 1) in reserved:
            primary = local - 1
            if any(u.device_id in {d.device_id for d in native_devices}
                   and u.channel == ch - 1 for u in performance.units):
                pair_mask |= 1 << (bank * 3 + primary // 3)
    emit_setup(0x05, 1, 1, 'OPL3 mode enable')
    if pair_mask:
        emit_setup(0x04, pair_mask, 1, 'OPL3 four-op pair enable')

    def run_units(device, units, resolve, tl_of, carrier_tl, missing_loss,
                  fixed_lanes=None):
        lanes = sorted({(u.device_id, u.channel) for u in units})
        local_map = {}
        for lane in lanes:
            if fixed_lanes and lane in fixed_lanes:
                local_map[lane] = fixed_lanes[lane]
                continue
            voice = None
            for u in units:
                if (u.device_id, u.channel) == lane:
                    voice = voice_by_id.get(_at(u.voice_curve, u.start_sample))
                    break
            p = dict(voice.parameters) if voice else {}
            width = 2 if len(p.get('operators', ())) == 4 else 1
            free = [ch for ch in range(18)
                    if ch not in local_map.values() and ch not in reserved
                    and (width == 1 or (ch % 9 in (0, 3, 6) and ch + 1 not in local_map.values()
                                        and ch + 1 not in reserved))]
            if free:
                local_map[lane] = free[0]
                if width == 2:
                    reserved.add(free[0] + 1)
        if len(local_map) < len(lanes) and not force:
            raise ValueError('YMF262 FM target capacity exceeded; force permits explicitly reported lane omission')
        allocation.update({str(k): v for k, v in local_map.items()})
        clock = device.clock_hz or (14318180 if device.chip == 'ymf262' else 3579545)
        target_clock = 14318180
        for unit in units:
            lane = (unit.device_id, unit.channel)
            if lane not in local_map:
                losses['opl3_fm_units_omitted_capacity'] += 1
                continue
            pitch_values = [_at(unit.pitch_curve, unit.start_sample),
                            *(hz for at, hz in unit.pitch_curve
                              if unit.start_sample <= at < unit.end_sample)]
            if any(hz is None or not math.isfinite(hz) or hz <= 0
                   for hz in pitch_values):
                losses[missing_loss] += 1
                continue
            ch = local_map[lane]
            times = sorted({unit.start_sample,
                            *(at for curve in (unit.pitch_curve, unit.volume_curve,
                                               unit.voice_curve)
                              for at, _ in curve
                              if unit.start_sample <= at < unit.end_sample)})
            state = {'pitch': None}
            previous = (object(), object(), object())

            def emit_voice(sample, row, level):
                fb, ops, connection, left, right = row
                four = len(ops) == 4
                for slot, op in enumerate(ops):
                    owner, oslot = _op_owner(ch, slot) if four else (ch, slot)
                    off = _OFFSETS[owner % 9] + 3 * oslot
                    emit(unit, sample, -0.5, owner, 0x20 + off,
                         (op[0] << 7) | (op[1] << 6) | (op[2] << 5) | (op[3] << 4) | op[4],
                         'OPL3 voice operator flags')
                    emit(unit, sample, -0.5, owner, 0x40 + off,
                         (op[5] << 6) | tl_of(row, slot, op, level),
                         'OPL3 voice operator level')
                    emit(unit, sample, -0.5, owner, 0x60 + off, (op[7] << 4) | op[8],
                         'OPL3 voice operator attack/decay')
                    emit(unit, sample, -0.5, owner, 0x80 + off, (op[9] << 4) | op[10],
                         'OPL3 voice operator sustain/release')
                    emit(unit, sample, -0.5, owner, 0xe0 + off, op[11],
                         'OPL3 voice operator waveform')
                if four:
                    cnt_p, cnt_s = connection & 1, (connection >> 1) & 1
                    emit(unit, sample, -0.5, ch, 0xc0 + ch % 9,
                         (left << 5) | (right << 4) | (fb << 1) | cnt_p,
                         'OPL3 voice feedback/connection')
                    emit(unit, sample, -0.5, ch + 1, 0xc0 + (ch + 1) % 9,
                         (left << 5) | (right << 4) | cnt_s,
                         'OPL3 voice connection (secondary)')
                else:
                    emit(unit, sample, -0.5, ch, 0xc0 + ch % 9,
                         (left << 5) | (right << 4) | (fb << 1) | connection,
                         'OPL3 voice feedback/connection')

            def emit_pitch(sample, hz):
                block, fnum = _pitch(hz, target_clock)
                state['pitch'] = (block, fnum)
                emit(unit, sample, -0.5, ch, 0xa0 + ch % 9, fnum & 255, 'OPL3 pitch low')
                emit(unit, sample, -0.5, ch, 0xb0 + ch % 9,
                     (1 << 5) | (block << 2) | (fnum >> 8), 'OPL3 pitch high/key')

            for sample in times:
                voice_id = _at(unit.voice_curve, sample)
                row = resolve(voice_id)
                if row is None:
                    losses['opl3_missing_voice'] += 1
                    continue
                level = _at(unit.volume_curve, sample)
                hz = _at(unit.pitch_curve, sample)
                if voice_id != previous[0]:
                    emit_voice(sample, row, level)
                elif level != previous[1]:
                    carrier_tl(unit, sample, ch, row, level, emit)
                if hz != previous[2]:
                    emit_pitch(sample, hz)
                previous = (voice_id, level, hz)
            if state['pitch'] is not None:
                block, fnum = state['pitch']
                emit(unit, unit.end_sample,
                     -1 if unit.end_sample > unit.start_sample else 1,
                     ch, 0xb0 + ch % 9, (block << 2) | (fnum >> 8), 'OPL3 gate end')

    def carriers_of(row):
        ops, connection = row[1], row[2]
        if len(ops) == 4:
            return (1, 2, 3) if connection == 3 else (3,)
        return (0, 1) if connection else (1,)

    def native_row(voice, *, stereo):
        p = dict(voice.parameters) if voice else {}
        if 'operators' not in p:
            return None
        ops = []
        for raw in p['operators']:
            o = dict(raw)
            ops.append((o['am'], o['vib'], o['egt'], o['ksr'], o['multiple'],
                        o['key_scale'], o['total_level'], o['attack'], o['decay'],
                        o['sustain_level'], o['release'], o.get('waveform') or 0))
        left = p.get('left') if stereo else 1
        right = p.get('right') if stereo else 1
        return (p['feedback'] or 0, ops, p['connection'] or 0,
                1 if left is None else left, 1 if right is None else right)

    def tl_native(row, slot, op, level):
        base = op[6] or 0
        if slot in carriers_of(row):
            level = 0 if level is None else max(0, min(63, int(level)))
            return min(63, base + level)
        return base

    def carrier_native(unit, sample, ch, row, level, emit):
        for slot in carriers_of(row):
            op = row[1][slot]
            owner, oslot = _op_owner(ch, slot) if len(row[1]) == 4 else (ch, slot)
            emit(unit, sample, -0.5, owner, 0x40 + _OFFSETS[owner % 9] + 3 * oslot,
                 (op[5] << 6) | tl_native(row, slot, op, level),
                 'OPL3 carrier level')

    # ---- OPLL melody -------------------------------------------------
    opll_devices = [d for d in performance.devices if d.chip == 'opll']
    if opll_devices:
        device = opll_devices[0]
        if len(opll_devices) > 1:
            losses['second_opll_device_melody_not_fm_projected'] += 1
        _doc, table = _table()
        resolved = {}

        def resolve_opll(voice_id):
            if voice_id in resolved:
                return resolved[voice_id]
            voice = voice_by_id.get(voice_id)
            p = dict(voice.parameters) if voice else {}
            inst = p.get('instrument')
            result = None
            if inst and inst in table:
                entry = table[inst]
                result = (entry['fb'],
                          [tuple(o[f] for f in _OP_FIELDS) + (0,) for o in entry['ops']],
                          entry.get('alg', 0), 1, 1)
            elif inst == 0:
                patch = p.get('custom_patch') or ()
                if any(b is None for b in patch):
                    losses['opll_custom_patch_bytes_unobserved'] += 1
                patch = tuple(0 if b is None else b for b in patch)
                patch = patch + (0,) * (8 - len(patch))
                decoded = _decode_patch(patch)
                result = (decoded['fb'],
                          [tuple(_identity_op(decoded[k])) + (0,)
                           for k in ('mod', 'car')], 0, 1, 1)
            resolved[voice_id] = result
            return result

        def tl_opll(row, slot, op, level):
            if slot == 0:
                return op[6]
            level = 15 if level is None else max(0, min(15, int(level)))
            return min(63, level << 2)

        def carrier_opll(unit, sample, ch, row, level, emit):
            level = 15 if level is None else max(0, min(15, int(level)))
            emit(unit, sample, -0.5, ch, 0x40 + _OFFSETS[ch % 9] + 3,
                 (row[1][1][5] << 6) | min(63, level << 2), 'OPL3 carrier level')

        run_units(device,
                  [u for u in performance.units
                   if u.device_id == device.device_id and u.section == 'fm'],
                  resolve_opll, tl_opll, carrier_opll,
                  'opll_unknown_pitch_units_muted')
        _project_opll_rhythm(performance, device, emit, losses)

    # ---- Y8950 native --------------------------------------------------
    y8950_devices = [d for d in performance.devices if d.chip == 'y8950']
    if y8950_devices:
        device = y8950_devices[0]
        if len(y8950_devices) > 1:
            losses['second_y8950_device_omitted'] += 1
        resolved = {}

        def resolve_y8950(voice_id):
            if voice_id not in resolved:
                resolved[voice_id] = native_row(voice_by_id.get(voice_id), stereo=False)
            return resolved[voice_id]

        run_units(device,
                  [u for u in performance.units
                   if u.device_id == device.device_id and u.section == 'fm'],
                  resolve_y8950, tl_native, carrier_native,
                  'y8950_unknown_pitch_units_muted')
        _project_native_rhythm(performance, device, emit, losses)

    # ---- YMF262 native -------------------------------------------------
    for device in native_devices:
        resolved = {}

        def resolve_native(voice_id):
            if voice_id not in resolved:
                resolved[voice_id] = native_row(voice_by_id.get(voice_id), stereo=True)
            return resolved[voice_id]

        fixed = {(u.device_id, u.channel): u.channel
                 for u in performance.units
                 if u.device_id == device.device_id and u.section == 'fm'}
        run_units(device,
                  [u for u in performance.units
                   if u.device_id == device.device_id and u.section == 'fm'],
                  resolve_native, tl_native, carrier_native,
                  'ymf262_unknown_pitch_units_muted', fixed_lanes=fixed)
        _project_native_rhythm(performance, device, emit, losses)

    return rows, losses, allocation


def _rhythm_template(emit, device_id):
    template = _commercial_rhythm()
    for ch in (6, 7, 8):
        entry = template[str(ch)]
        off = _OFFSETS[ch]
        for slot, key in enumerate(('mod', 'car')):
            b20, b40, b60, b80 = entry[key]
            o = off + 3 * slot
            emit(None, 0, -2, ch, 0x20 + o, b20, 'OPL3 rhythm voice',
                 device_id=device_id)
            tl = 63 if 0x40 + o in _RHYTHM_TL.values() else (b40 & 63)
            emit(None, 0, -2, ch, 0x40 + o, (b40 & 0xc0) | tl,
                 'OPL3 rhythm voice', device_id=device_id)
            emit(None, 0, -2, ch, 0x60 + o, b60, 'OPL3 rhythm voice',
                 device_id=device_id)
            emit(None, 0, -2, ch, 0x80 + o, b80, 'OPL3 rhythm voice',
                 device_id=device_id)
        emit(None, 0, -2, ch, 0xc0 + ch, entry['fb_cnt'], 'OPL3 rhythm voice',
             device_id=device_id)


def _project_opll_rhythm(performance, device, emit, losses):
    events = [e for e in performance.percussion if e.device_id == device.device_id]
    if not events:
        return
    _rhythm_template(emit, device.device_id)
    pitches = _opll_rhythm_pitches(performance, device)
    bits = dict(_RHYTHM_BITS)
    actions = []
    for e in events:
        if e.instrument_family not in bits:
            losses['opl3_rhythm_family_unmapped'] += 1
            continue
        stop = e.stop_sample if e.stop_sample is not None else e.start_sample + 735
        actions.append((e.start_sample, 1, e))
        actions.append((stop, 0, e))
    actions.sort(key=lambda row: (row[0], row[1]))
    mask = 0
    for sample, is_start, e in actions:
        bit = bits[e.instrument_family]
        if is_start:
            for at, level in e.volume_curve:
                if level is None:
                    continue
                emit(None, at, -0.5, 6, _RHYTHM_TL[e.instrument_family],
                     min(63, int(level) << 2), 'OPL3 rhythm level',
                     device_id=device.device_id)
            if not e.volume_curve:
                losses['opll_rhythm_level_unobserved'] += 1
            ch = _RHYTHM_PITCH_CH.get(e.instrument_family)
            if ch is not None:
                state = {}
                for at, snapshot in pitches:
                    if at > e.start_sample:
                        break
                    state = snapshot
                fnum, block = state.get(ch, (None, None))
                if fnum is None:
                    losses['opll_rhythm_pitch_unobserved'] += 1
                else:
                    clock = device.clock_hz or 3579545
                    hz = fnum * clock / 72 * 2 ** block / 2 ** 19
                    block2, fnum2 = _pitch(hz, 14318180)
                    emit(None, e.start_sample, -0.5, ch, 0xa0 + ch, fnum2 & 255,
                         'OPL3 rhythm pitch', device_id=device.device_id)
                    emit(None, e.start_sample, -0.5, ch, 0xb0 + ch,
                         (block2 << 2) | (fnum2 >> 8), 'OPL3 rhythm pitch',
                         device_id=device.device_id)
            mask |= bit
        else:
            mask &= ~bit
        emit(None, sample, 0, 6, 0xbd, 0xe0 | mask, 'OPL3 rhythm key',
             device_id=device.device_id)


def _opll_rhythm_pitches(performance, device):
    state = {}
    result = []
    for c in performance.controls:
        if c.device_id != device.device_id:
            continue
        p = dict(c.parameters)
        if c.kind == 'opll_pitch_low':
            fnum, block = state.get(c.channel, (0, 0))
            state[c.channel] = (p['fnum_low'] | (fnum & 0x100), block)
        elif c.kind == 'opll_pitch_high':
            fnum, block = state.get(c.channel, (0, 0))
            state[c.channel] = ((fnum & 0xff) | (p['fnum_high'] << 8), p['block'])
        result.append((c.sample, dict(state)))
    return result


def _project_native_rhythm(performance, device, emit, losses):
    """Re-emit a Y8950/YMF262 source's rhythm state on bank 0."""
    events = [e for e in performance.percussion if e.device_id == device.device_id]
    if not events:
        return
    from native_registers import encode_control
    controls = {c.control_id: c for c in performance.controls}
    emitted = {}
    bits = dict(_RHYTHM_BITS)
    actions = []
    for e in events:
        if e.instrument_family not in bits:
            losses['opl3_rhythm_family_unmapped'] += 1
            continue
        stop = e.stop_sample if e.stop_sample is not None else e.start_sample + 735
        actions.append((e.start_sample, 1, e))
        actions.append((stop, 0, e))
    actions.sort(key=lambda row: (row[0], row[1]))
    mask = 0
    for sample, is_start, e in actions:
        bit = bits[e.instrument_family]
        if is_start:
            start_order = None
            if e.control_ids:
                first = controls.get(e.control_ids[0])
                if first is not None:
                    start_order = first.order
            registers = {}
            for c in performance.controls:
                if c.device_id != device.device_id:
                    continue
                if c.sample > e.start_sample:
                    break
                if (c.sample == e.start_sample and start_order is not None
                        and c.order >= start_order):
                    continue
                encoded = encode_control(c, device)
                if encoded[0] in (0x5c, 0x5e):
                    registers[encoded[1]] = encoded[2]
            for ch in (6, 7, 8):
                off = _OFFSETS[ch]
                for register in ([0x20 + off + 3 * s + group
                                  for group in (0, 0x20, 0x40, 0x60)
                                  for s in (0, 1)]
                                 + [0xc0 + ch, 0xa0 + ch, 0xb0 + ch]):
                    if register not in registers:
                        continue
                    value = registers[register]
                    if register == 0xb0 + ch:
                        value &= 0x1f
                    if emitted.get(register) != value:
                        emit(None, e.start_sample, -0.5, ch, register, value,
                             'OPL3 rhythm voice state', device_id=device.device_id)
                        emitted[register] = value
            for at, level in e.volume_curve:
                if level is None:
                    continue
                register = _RHYTHM_TL[e.instrument_family]
                emit(None, at, -0.5, 6, register, min(63, int(level)),
                     'OPL3 rhythm level', device_id=device.device_id)
                emitted[register] = min(63, int(level))
            mask |= bit
        else:
            mask &= ~bit
        emit(None, sample, 0, 6, 0xbd, 0xe0 | mask, 'OPL3 rhythm key',
             device_id=device.device_id)
